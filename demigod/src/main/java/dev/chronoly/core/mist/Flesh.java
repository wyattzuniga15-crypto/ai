package dev.chronoly.core.mist;

/** What the thing being hit is made of, as far as the Mist is concerned. */
public enum Flesh {
    /** Villagers, vanilla mobs, ordinary people. They cannot even see the monsters. */
    MORTAL,
    /** Anything that dissolves into golden dust and reforms in Tartarus. */
    MONSTER,
    /** Half and half, and hurt by both. This is the whole tragedy of the books. */
    DEMIGOD,
    /** Gods, Titans, and their avatars. Only the divine touches them at all. */
    IMMORTAL
}
