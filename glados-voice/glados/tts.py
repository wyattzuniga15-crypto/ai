def tts_python(ws: Workspace) -> Path:
    v = ws.env / "tts"
    return v / "Scripts" / "python.exe" if os.name == "nt" else v / "bin" / "python"


def tts_env(ws: Workspace, gpu: dict, workers: int = 4) -> dict:
    extra = {"HF_HOME": str(ws.tools / "hf-cache"), "GLADOS_TTS_WORKERS": str(workers),
             "TOKENIZERS_PARALLELISM": "false", "WANDB_MODE": "disabled"}
    if gpu.get("device") == "cuda":
        extra.update(CUDA_DEVICE_ORDER="PCI_BUS_ID", CUDA_VISIBLE_DEVICES=gpu["cuda_visible_devices"],
                     ACCELERATE_MIXED_PRECISION="bf16")
    else:
        extra.update(CUDA_VISIBLE_DEVICES="", ACCELERATE_MIXED_PRECISION="no")
    return child_env(extra)


def side(ws: Workspace, gpu: dict, script: str, *args, log_name="tts.log", on_line=None, check=True, workers=4):
    return run([tts_python(ws), SIDE / script, *args], cwd=ws.root, env=tts_env(ws, gpu, workers),
               log_name=log_name, logs_dir=ws.logs, on_line=on_line, check=check)


def words(text: str) -> list[str]:
    return re.sub(r"[^a-z0-9' ]+", " ", text.lower().replace("-", " ")).split()


def similarity(a: str, b: str) -> float:
    wa, wb = words(a), words(b)
    if not wa or not wb:
        return 0.0
    return difflib.SequenceMatcher(a=wa, b=wb).ratio()


def wer(ref: str, hyp: str) -> float:
    r, h = words(ref), words(hyp)
    if not r:
        return 1.0
    d = list(range(len(h) + 1))
    for i in range(1, len(r) + 1):
        prev, d[0] = d[0], i
        for j in range(1, len(h) + 1):
            cur = d[j]
            d[j] = min(d[j] + 1, d[j - 1] + 1, prev + (r[i - 1] != h[j - 1]))
            prev = cur
    return d[len(h)] / len(r)


def asr(ws: Workspace, gpu: dict, files: list[Path], out_json: Path, model: str) -> dict[str, str]:
    """Whisper transcripts {path: text}; {} if Whisper can't be loaded (e.g. offline)."""
    job = out_json.with_suffix(".job.json")
    write_json(job, {"files": [str(f) for f in files], "model": model})
    rc, tail, _ = side(ws, gpu, "transcribe.py", job, out_json, check=False)
    if rc == 3 or rc != 0:
        LOG.warning("Whisper is unavailable (%s); continuing without it",
                    next((line for line in tail if line.startswith("ASR_UNAVAILABLE")), f"exit {rc}"))
        return {}
    return read_json(out_json, {}) or {}


def reference_stats(ws: Workspace) -> dict:
    from .tune import reference
    return reference(ws)


def timbre(path: Path, ref: dict) -> float:
    x, sr = A.read_wav(path)
    m = EV._active_mfcc(x, sr)
    if len(m) < 20:
        return float("nan")
    return EV.frechet(m.mean(axis=0), np.cov(m, rowvar=False), ref["mu"], ref["cov"])


