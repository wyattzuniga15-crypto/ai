def step_setup(ws: Workspace, a) -> dict:
    py = tts_python(ws)
    if not py.exists():
        LOG.info("Creating the TTS venv (Python 3.12)")
        run([a.uv, "venv", ws.env / "tts", "--python", "3.12"], log_name="setup.log", logs_dir=ws.logs)
    marker = ws.env / "tts" / f".glados_f5_{F5_VERSION}"
    if a.allow_cpu:
        if not marker.exists():
            run([a.uv, "pip", "install", "--python", py, f"torch=={AP.TORCH_VERSION}",
                 f"torchaudio=={AP.TORCH_VERSION}", f"f5-tts=={F5_VERSION}", "soundfile", "soxr"],
                log_name="setup.log", logs_dir=ws.logs)
    else:
        info = AP._torch_info(ws, py)
        idx = ("cu" + info["cuda_build"].replace(".", "")) if info and info.get("cuda_build") else None
        if not (info and info["cuda_build"] and info["cuda_available"]):
            idx = AP._install_torch(ws, a.uv, reinstall=bool(info), python=py)
        if not marker.exists():
            LOG.info("Installing F5-TTS %s", F5_VERSION)
            run([a.uv, "pip", "install", "--python", py, f"f5-tts=={F5_VERSION}", "soundfile", "soxr",
                 "--extra-index-url", f"https://download.pytorch.org/whl/{idx}", "--index-strategy",
                 "unsafe-best-match"], log_name="setup.log", logs_dir=ws.logs)
        info = AP._torch_info(ws, py)
        if not (info and info["cuda_build"] and info["cuda_available"]):
            AP._install_torch(ws, a.uv, reinstall=True, python=py)
    marker.write_text(now())
    info = AP._torch_info(ws, py) or {}
    return {"f5_tts": F5_VERSION, "torch": info.get("version"), "cuda": info.get("cuda_build")}


def step_transcripts(ws: Workspace, a, gpu: dict, state: State) -> dict:
    manifest = {r["id"]: r["rel_path"] for r in csv.DictReader(open(ws.raw / "manifest.csv", encoding="utf-8"))}
    lines = [(p, "train") for p in sorted(ws.dataset.glob("*.wav"))] + \
            [(p, "holdout") for p in sorted(ws.holdout.glob("*.wav"))]
    game = state.info("locate").get("game_dir")
    captions = read_game_captions(Path(game)) if game and Path(game).exists() else {}
    tdir = ws.root / "tts"
    tdir.mkdir(parents=True, exist_ok=True)
    heard = asr(ws, gpu, [p for p, _ in lines], tdir / "whisper.json", a.asr_model)
    rows, counts = [], {"caption, confirmed by Whisper": 0, "Whisper (caption differs)": 0,
                        "Whisper (no caption)": 0, "caption (not checked: no Whisper)": 0, "no text": 0}
    for p, split in lines:
        rel = manifest.get(p.stem, "").lower()
        cap = captions.get(rel, "")
        whi = heard.get(str(p), "")
        sim = similarity(cap, whi) if cap and whi else None
        if cap and whi:
            text, src = (cap, "caption, confirmed by Whisper") if sim >= 0.75 else (whi, "Whisper (caption differs)")
        elif whi:
            text, src = whi, "Whisper (no caption)"
        elif cap:
            text, src = cap, "caption (not checked: no Whisper)"
        else:
            text, src = "", "no text"
        counts[src] += 1
        rows.append({"id": p.stem, "split": split, "text": text, "source": src,
                     "similarity": "" if sim is None else round(sim, 3), "caption": cap, "whisper": whi,
                     "seconds": round(A.read_wav(p)[0].size / A.TARGET_SR, 2)})
    with open(tdir / "transcripts.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    usable = sum(1 for r in rows if r["text"] and r["split"] == "train")
    min_lines = getattr(a, "min_lines", 20)
    LOG.info("Transcripts for %d lines -> %s: %s", len(rows), tdir / "transcripts.csv",
             ", ".join(f"{v} {k}" for k, v in counts.items() if v))
    if usable < min_lines:
        raise Blocked(f"Only {usable} training lines have a transcript. Whisper needs internet access to "
                      "download its model the first time; check the connection and re-run tts.bat.")
    return {"lines": len(rows), "usable_train": usable, **{k: v for k, v in counts.items() if v}}


def _transcripts(ws: Workspace) -> list[dict]:
    return list(csv.DictReader(open(ws.root / "tts" / "transcripts.csv", encoding="utf-8")))


def step_dataset(ws: Workspace, gpu: dict) -> dict:
    items = [{"audio": str((ws.dataset / f"{r['id']}.wav").resolve()), "text": r["text"]}
             for r in _transcripts(ws) if r["split"] == "train" and r["text"]]
    job = ws.root / "tts" / "dataset_items.json"
    write_json(job, {"items": items})
    rc, tail, _ = side(ws, gpu, "prepare.py", job)
    res = AP.json_line(tail, "PREPARE_JSON ")
    if not res:
        raise StepFailed("Writing the F5-TTS dataset failed:\n" + "\n".join(tail[-15:]))
    LOG.info("F5-TTS fine-tuning set: %d lines, %.1f min (%d skipped: empty or outside 0.3-30 s)",
             res["lines"], res["minutes"], res["skipped"])
    return res


class _Slimmer(threading.Thread):
    """Shrinks each finished intermediate checkpoint to fp16 EMA weights while training runs."""

    def __init__(self, ws: Workspace, gpu: dict, ckpts: Path):
        super().__init__(daemon=True)
        self.ws, self.gpu, self.ckpts, self.stop = ws, gpu, ckpts, threading.Event()
        self.seen: dict[str, tuple] = {}
        self.lock = threading.Lock()

    def sweep(self, final: bool = False):
        with self.lock:
            self._sweep(final)

    def _sweep(self, final: bool):
        for p in sorted(self.ckpts.glob("model_*.pt")):
            if p.name == "model_last.pt" or not re.fullmatch(r"model_\d+\.pt", p.name) or not p.exists():
                continue
            st = p.stat()
            key = (st.st_size, st.st_mtime_ns)
            stable = self.seen.get(p.name) == key and time.time() - st.st_mtime > 30
            self.seen[p.name] = key
            if stable or final:
                run([tts_python(self.ws), SIDE / "slim.py", p, p.with_name("ema_" + p.name[len("model_"):])],
                    cwd=self.ws.root, env=tts_env(self.ws, {"device": "cpu"}), log_name="tts_train.log",
                    logs_dir=self.ws.logs, check=False, quiet=True)

    def run(self):
        while not self.stop.wait(30):
            try:
                self.sweep()
            except Exception as exc:
                LOG.debug("slimmer: %s", exc)


def _drop_broken_checkpoints(ckpts: Path):
    """A save cut short (power loss, full disk) leaves a truncated .pt that F5-TTS would try
    to resume from and crash on. PyTorch checkpoints are zip files: if one won't open, delete it
    so training resumes from the newest intact one."""
    import zipfile

    for p in sorted(ckpts.glob("model_*.pt")) + sorted(ckpts.glob("*.part")):
        try:
            if p.suffix == ".part":
                raise zipfile.BadZipFile("partial")
            zipfile.ZipFile(p).close()
        except (zipfile.BadZipFile, OSError) as exc:
            LOG.warning("Removing damaged checkpoint %s (%s)", p.name, exc)
            p.unlink(missing_ok=True)


def step_train(ws: Workspace, a, gpu: dict, state: State) -> dict:
    prep = state.info("tts_dataset")
    live = state.step("tts_train").setdefault("info", {})
    frames = prep["minutes"] * 60 * 24000 / 256
    batch = int(live.get("batch_frames", a.batch_frames))
    ckpts = Path(prep["ckpts"])
    ckpts.mkdir(parents=True, exist_ok=True)
    free = disk_free_gb(ckpts)
    if free < a.min_free_gb:
        raise Blocked(f"Only {free:.0f} GB free on the drive holding {ckpts}; F5-TTS fine-tuning needs about "
                      f"{a.min_free_gb:g} GB while it runs. Free some space and run tts.bat again.")
    while True:
        per_epoch = max(1, math.ceil(frames / batch))
        epochs = max(1, math.ceil(a.updates / per_epoch))
        save_per = a.save_per or max(1, a.updates // 5)
        args = ["--exp_name", "F5TTS_v1_Base", "--dataset_name", "GLaDOS", "--finetune", "--tokenizer", "pinyin",
                "--learning_rate", "1e-5", "--batch_size_per_gpu", batch, "--batch_size_type", "frame",
                "--max_samples", "64", "--epochs", epochs, "--num_warmup_updates", max(1, min(1000, a.updates // 10)),
                "--save_per_updates", save_per, "--last_per_updates", max(1, min(500, a.updates // 20)),
                "--keep_last_n_checkpoints", "6"]
        if a.f5_pretrain:
            args += ["--pretrain", a.f5_pretrain]
        if gpu.get("device") == "cuda" and not live.get("no_bnb"):
            args += ["--bnb_optimizer"]
        LOG.info("Fine-tuning F5-TTS: about %d updates (%d epochs of ~%d), %d frames per batch; checkpoints in %s",
                 a.updates, epochs, per_epoch, batch, ckpts)
        mon = {"oom": False, "ram": False, "done": False}

        def on_line(line):
            if any(m in line for m in AP.OOM_MARKERS):
                mon["oom"] = True
                return "kill"
            if "MemoryError" in line or "can't allocate memory" in line or "not enough memory" in line:
                mon["ram"] = True
                return "kill"
            if "FINETUNE_DONE" in line:
                mon["done"] = True
            return None

        _drop_broken_checkpoints(ckpts)
        slimmer = _Slimmer(ws, gpu, ckpts)
        slimmer.start()
        workers = int(live.get("workers", 4))
        rc, tail, _ = side(ws, gpu, "finetune.py", *args, log_name="tts_train.log", on_line=on_line, check=False,
                           workers=workers)
        slimmer.stop.set()
        slimmer.join(timeout=600)
        slimmer.sweep(final=True)
        if rc in (-9, 137) and not mon["done"]:
            mon["ram"] = True  # killed by the system: nearly always out of RAM
        if mon["ram"]:
            if workers <= 1 and batch <= 400:
                raise Blocked("F5-TTS fine-tuning runs out of system memory (RAM) even with minimal settings. "
                              "Close other programs and run tts.bat again.")
            live["workers"] = 1
            batch = max(400, int(batch * 0.7))
            live["batch_frames"] = batch
            state.save()
            LOG.warning("Out of system memory; retrying with one data-loader worker and %d frames per batch", batch)
            continue
        if mon["oom"]:
            if batch <= 400:
                raise Blocked("F5-TTS runs out of GPU memory even at small batches. Close other programs "
                              "using the GPU and run tts.bat again.")
            batch = int(batch * 0.7)
            live["batch_frames"] = batch
            state.save()
            LOG.warning("Out of GPU memory; resuming with %d frames per batch", batch)
            continue
        if rc == 0 and mon["done"]:
            break
        if not live.get("no_bnb") and any("bitsandbytes" in line.lower() for line in tail):
            # 8-bit Adam could not load (a DLL/CUDA mismatch on some Windows setups): use
            # standard AdamW, which needs more memory, so start from a smaller batch.
            live["no_bnb"] = True
            batch = int(batch * 0.75)
            live["batch_frames"] = batch
            state.save()
            LOG.warning("8-bit Adam (bitsandbytes) failed to load; continuing with standard AdamW and "
                        "%d frames per batch", batch)
            continue
        live["restarts"] = live.get("restarts", 0) + 1
        state.save()
        if live["restarts"] > 3:
            raise StepFailed("F5-TTS fine-tuning keeps failing:\n" + "\n".join(tail[-30:]))
        LOG.warning("Fine-tuning stopped (exit %s); resuming from its last checkpoint", rc)
    saved = sorted(p.name for p in list(ckpts.glob("ema_*.pt")) + list(ckpts.glob("model_*.pt")))
    return {"updates": a.updates, "batch_frames": batch, "checkpoints": saved, "ckpt_dir": str(ckpts)}


def _pick_reference(rows: list[dict]) -> dict:
    good = [r for r in rows if r["split"] == "train" and r["text"] and 4.0 <= float(r["seconds"]) <= 9.0]
    good.sort(key=lambda r: (not r["source"].startswith("caption, confirmed"), abs(float(r["seconds"]) - 7.0)))
    if not good:
        good = sorted((r for r in rows if r["split"] == "train" and r["text"]), key=lambda r: -float(r["seconds"]))
    if not good:
        raise StepFailed("No transcribed line is usable as the TTS voice reference")
    return good[0]


def step_select(ws: Workspace, a, gpu: dict, state: State) -> dict:
    tr = state.info("tts_train")
    ckdir = Path(tr["ckpt_dir"])
    def update_no(p: Path) -> int:
        m = re.search(r"(\d+)", p.stem)
        return int(m.group(1)) if m else 0

    snaps = sorted(list(ckdir.glob("ema_*.pt")) + [p for p in ckdir.glob("model_*.pt") if p.name != "model_last.pt"],
                   key=update_no)
    last = [ckdir / "model_last.pt"] if (ckdir / "model_last.pt").exists() else []
    base = sorted(ckdir.glob("pretrained_*"))
    cands = base[:1] + snaps + last
    rows = _transcripts(ws)
    ref = _pick_reference(rows)
    ref_wav = ws.root / "tts" / "reference.wav"
    x, sr = A.read_wav(ws.dataset / f"{ref['id']}.wav")
    A.write_wav16(ref_wav, A.resample(x, sr, 24000), 24000)
    tests = [r for r in rows if r["split"] == "holdout" and r["text"]][:6]
    if not tests:
        tests = [r for r in rows if r["split"] == "train" and r["text"] and r["id"] != ref["id"]][:6]
    vocab = str(Path(state.info("tts_dataset")["vocab"]))
    sel_dir = ws.root / "tts" / "select"
    results = []
    refstats = reference_stats(ws)
    for ck in cands:
        outs = [sel_dir / ck.stem / f"{t['id']}.wav" for t in tests]
        job = {"ckpt": str(ck), "vocab": vocab, "vocoder_local": a.vocoder_local, "ref_audio": str(ref_wav),
               "ref_text": ref["text"], "nfe_step": a.nfe_step,
               "items": [{"text": t["text"], "out": str(o), "seed": 1234} for t, o in zip(tests, outs)]}
        write_json(sel_dir / f"{ck.stem}.job.json", job)
        side(ws, gpu, "generate.py", sel_dir / f"{ck.stem}.job.json", log_name="tts_select.log")
        results.append({"ckpt": ck, "outs": outs})
    heard = asr(ws, gpu, [o for r in results for o in r["outs"]], sel_dir / "whisper.json", a.asr_model)
    for r in results:
        r["wer"] = float(np.mean([wer(t["text"], heard[str(o)]) for t, o in zip(tests, r["outs"])])) if heard else float("nan")
        r["timbre"] = float(np.nanmean([timbre(o, refstats) for o in r["outs"]]))
    med = float(np.nanmedian([r["timbre"] for r in results])) or 1.0
    for r in results:
        r["score"] = (2.0 * r["wer"] if np.isfinite(r["wer"]) else 0.0) + r["timbre"] / med
    best = min(results, key=lambda r: r["score"])
    table = [{"checkpoint": r["ckpt"].name, "word_error_rate": None if not np.isfinite(r["wer"]) else round(r["wer"], 3),
              "timbre_distance": round(r["timbre"], 3), "score": round(r["score"], 3)} for r in results]
    write_json(ws.root / "tts" / "selection.json", {"chosen": best["ckpt"].name, "table": table,
                                                    "reference": ref, "tests": [t["id"] for t in tests]})
    for row in table:
        LOG.info("   %-40s WER %-6s timbre %-8s score %.3f%s", row["checkpoint"], row["word_error_rate"],
                 row["timbre_distance"], row["score"], "  <- chosen" if row["checkpoint"] == best["ckpt"].name else "")
    if not heard:
        LOG.warning("Chosen on timbre only (no Whisper, so pronunciation errors were not measured)")
    return {"ckpt": str(best["ckpt"]), "chosen": best["ckpt"].name, "vocab": vocab, "ref_audio": str(ref_wav),
            "ref_text": ref["text"], "used_whisper": bool(heard)}


