def slug(text: str, n: int = 40) -> str:
    return (re.sub(r"[^A-Za-z0-9]+", "_", text).strip("_")[:n] or "line").lower()


def speak(ws: Workspace, a, gpu: dict, state: State, texts: list[str]) -> Path:
    sel = state.info("tts_select")
    stamp = _dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    out = ws.root / "tts" / "out" / f"{stamp}_{slug(texts[0])}"
    items = []
    for li, text in enumerate(texts, 1):
        for k in range(1, a.takes + 1):
            items.append({"text": text, "out": str(out / "raw" / f"line{li:02d}_take{k}.wav"),
                          "seed": 1000 * li + k, "line": li, "take": k})
    job = {"ckpt": sel["ckpt"], "vocab": sel["vocab"], "vocoder_local": a.vocoder_local,
           "ref_audio": sel["ref_audio"], "ref_text": sel["ref_text"], "nfe_step": a.nfe_step, "items": items}
    write_json(out / "generate.job.json", job)
    LOG.info("Generating %d take(s) of %d line(s) with %s", a.takes, len(texts), Path(sel["ckpt"]).name)
    side(ws, gpu, "generate.py", out / "generate.job.json", log_name="tts_speak.log")

    pth, idx = V.model_files(ws)
    s = V.Settings(pitch=0, index_rate=a.index_rate, protect=0.33, autotune_strength=a.steps)
    pairs = [(Path(it["out"]), out / "rvc" / Path(it["out"]).name) for it in items]
    for _, o in pairs:
        o.unlink(missing_ok=True)
    V.run_jobs(ws, [V.job(pth, idx, s, pairs)], out / "rvc.job.json", "tts_speak.log")

    heard = asr(ws, gpu, [o for _, o in pairs], out / "whisper.json", a.asr_model) if not a.no_rank_asr else {}
    refstats = reference_stats(ws)
    rows = []
    for it, (_, o) in zip(items, pairs):
        w = wer(it["text"], heard[str(o)]) if heard else float("nan")
        rows.append({"line": it["line"], "take": it["take"], "text": it["text"], "file": o,
                     "word_error_rate": w, "heard": heard.get(str(o), ""), "timbre": timbre(o, refstats)})
    with open(out / "ranking.csv", "w", newline="", encoding="utf-8") as fh:
        wtr = csv.writer(fh)
        wtr.writerow(["line", "rank", "take", "word_error_rate", "timbre_distance", "file", "text", "whisper_heard"])
        for li in range(1, len(texts) + 1):
            takes = sorted((r for r in rows if r["line"] == li),
                           key=lambda r: ((r["word_error_rate"] if np.isfinite(r["word_error_rate"]) else 0), r["timbre"]))
            for rank, r in enumerate(takes, 1):
                wtr.writerow([li, rank, r["take"], "" if not np.isfinite(r["word_error_rate"]) else round(r["word_error_rate"], 3),
                              round(r["timbre"], 3), r["file"].name, r["text"], r["heard"]])
            shutil.copyfile(takes[0]["file"], out / f"line{li:02d}_best.wav")
            V.concat_with_gaps([r["file"] for r in takes], out / f"line{li:02d}_all_takes.wav")
            LOG.info("Line %d: best is take %d%s -> %s", li, takes[0]["take"],
                     f" (Whisper heard: \"{takes[0]['heard']}\")" if takes[0]["heard"] else "", out / f"line{li:02d}_best.wav")
    LOG.info("All takes (ranked) in %s; ranking.csv explains the order", out)
    return out


# ----------------------------------------------------------------------------- CLI

def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="tts.bat", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("text", nargs="*", help="line(s) to speak; none = just build the model")
    ap.add_argument("--file", help="text file, one line per row")
    ap.add_argument("--takes", type=int, default=5)
    ap.add_argument("--steps", type=float, default=0.0, help="GLaDOS-mode step strength on the RVC pass (0-1)")
    ap.add_argument("--index-rate", type=float, default=0.5, help="RVC index rate for the polish pass")
    ap.add_argument("--nfe-step", type=int, default=32, help="F5-TTS sampling steps (quality vs speed)")
    ap.add_argument("--updates", type=int, default=20000, help="fine-tuning length in optimiser updates")
    ap.add_argument("--batch-frames", type=int, default=1536, help="starting batch size in mel frames (8 GB default)")
    ap.add_argument("--redo", choices=[s for s, _ in STEPS], help="redo this build step and the ones after it")
    ap.add_argument("--root", default=r"C:\GLaDOSVoice")
    ap.add_argument("--uv", help=argparse.SUPPRESS)
    ap.add_argument("--asr-model", default=ASR_MODEL, help=argparse.SUPPRESS)
    ap.add_argument("--f5-pretrain", help=argparse.SUPPRESS)      # local base checkpoint (offline/testing)
    ap.add_argument("--vocoder-local", help=argparse.SUPPRESS)    # local Vocos folder (offline/testing)
    ap.add_argument("--no-rank-asr", action="store_true", help=argparse.SUPPRESS)
    ap.add_argument("--allow-cpu", action="store_true", help=argparse.SUPPRESS)
    ap.add_argument("--min-lines", type=int, default=20, help=argparse.SUPPRESS)
    ap.add_argument("--save-per", type=int, help=argparse.SUPPRESS)
    ap.add_argument("--min-free-gb", type=float, default=15.0, help=argparse.SUPPRESS)
    a = ap.parse_args(argv)

    ws = Workspace(Path(a.root))
    setup_logging(ws)
    state = State(ws.state_file)
    if not state.is_done("export"):
        raise Blocked("Build the voice model first: run run.bat until it finishes, then tts.bat.")
    gpu = V.gpu_for_tools(ws)
    if a.allow_cpu:
        gpu = {"device": "cpu"}
    if not a.uv:
        cands = [ws.tools / "uv" / ("uv.exe" if os.name == "nt" else "uv"), shutil.which("uv")]
        a.uv = next((str(c) for c in cands if c and Path(c).exists()), None)
        if not a.uv:
            raise Blocked("uv was not found; start tts.bat (it goes through run.ps1, which installs uv).")
    if a.redo:
        first = [s for s, _ in STEPS].index(a.redo)
        for name, _ in STEPS[first:]:
            state.reset(name)

    runners = {"tts_setup": lambda: step_setup(ws, a),
               "tts_transcripts": lambda: step_transcripts(ws, a, gpu, state),
               "tts_dataset": lambda: step_dataset(ws, gpu),
               "tts_train": lambda: step_train(ws, a, gpu, state),
               "tts_select": lambda: step_select(ws, a, gpu, state)}
    for i, (name, title) in enumerate(STEPS, 1):
        if state.is_done(name):
            continue
        LOG.info("[TTS %d/%d] %s", i, len(STEPS), title)
        state.mark(name, "running")
        t0 = time.time()
        try:
            info = runners[name]()
        except (Blocked, StepFailed):
            state.mark(name, "failed")
            raise
        state.mark(name, "done", {**info, "seconds": round(time.time() - t0)})
        LOG.info("[TTS %d/%d] done in %s", i, len(STEPS), fmt_duration(time.time() - t0))

    texts = list(a.text)
    if a.file:
        texts += [t.strip() for t in Path(a.file).read_text(encoding="utf-8").splitlines() if t.strip()]
    if not texts:
        LOG.info("TTS model ready (%s). Try: tts.bat \"Hello. It's been a long time.\"",
                 state.info("tts_select").get("chosen"))
        return 0
    speak(ws, a, gpu, state, texts)
    return 0
