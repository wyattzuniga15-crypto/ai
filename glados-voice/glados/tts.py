"""Optional TTS stage (tts.bat): type a line, get several GLaDOS takes.

  tts.bat                                   build (or resume building) the TTS model
  tts.bat "Oh. It's you."                   5 takes of that line
  tts.bat "Line one" "Line two" --takes 8
  tts.bat --file lines.txt                  one line per row
  tts.bat "..." --steps 0.6                 GLaDOS-mode steps on the RVC pass

Building (first run, resumable like run.bat):
  1. transcripts: the game's own captions for each clean line, checked against
     Whisper; where they disagree (or there is no caption) Whisper's text is used
  2. an F5-TTS fine-tuning set from the clean training lines (held-out lines stay out)
  3. fine-tune F5-TTS (bf16, 8-bit Adam, sized for 8 GB; smaller batches on out-of-memory)
  4. pick the best checkpoint by synthesising the held-out lines' text and scoring
     intelligibility (Whisper word error rate) and timbre against her real held-out lines;
     the untuned base model competes too, so fine-tuning can't make things worse

Speaking: each take is generated by F5-TTS, then run through the RVC model (pitch 0: it's
already her voice; RVC tightens the timbre), then ranked by word errors and timbre. Every
take is kept; <line>_best.wav is the top one and <line>_all_takes.wav plays them in rank order.
Recorded/typed lines only: this cannot run live inside voice.ai.
"""

